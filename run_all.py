"""
Regenerate every figure (figures/) and every results table (results/results.md).

    python run_all.py
"""

import os
import numpy as np
import experiments as ex

RES = os.path.join(os.path.dirname(__file__), "results")
os.makedirs(RES, exist_ok=True)


def num(x, nd=3, scale=1.0, unit=""):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "never"
    return f"{x*scale:.{nd}f}{unit}"


def metric_cols(r):
    return [num(r["rise_time"], 0, 1000, " ms"), f"{r['overshoot']:.1f} %",
            num(r["settling_time"], 0, 1000, " ms"), num(r["ss_error"], 1, 1000, " mm")]


def table(title, header, rows):
    out = [f"\n### {title}\n", "| " + " | ".join(header) + " |",
           "|" + "---|" * len(header)]
    out += ["| " + " | ".join(map(str, r)) + " |" for r in rows]
    return "\n".join(out) + "\n"


def main():
    md = ["# Results (auto-generated by run_all.py)\n",
          "Rise time is 10→90 % of the final value; settling is ±2 % of the final value; "
          "steady-state error = setpoint − final value.\n"]
    M = ["rise time", "overshoot", "settling (2 %)", "ss error"]

    print("Section 1"); ex.fig_feedback_loop()
    print("Section 3"); ex.fig_open_loop()
    print("Section 4")
    m = ex.fig_metrics_annotated()
    md.append(table("Section 4 - Fig 3 example (P-only, Kp = 150)", M, [metric_cols(m)]))

    print("Section 5")
    rows = ex.fig_p_only()
    md.append(table("Section 5 - P only: calculation vs simulation",
                    ["Kp", "ss error predicted 20/(20+Kp)", "ss error simulated", "ζ = 10/(2√(20+Kp))",
                     "overshoot predicted", "overshoot simulated", "rise time", "settling (2 %)"],
                    [[r["Kp"], num(r["ess_pred"], 1, 1000, " mm"), num(r["ess_sim"], 1, 1000, " mm"),
                      f"{r['zeta']:.3f}", f"{r['os_pred']:.1f} %", f"{r['os_sim']:.1f} %",
                      num(r["rise"], 0, 1000, " ms"), num(r["settle"], 0, 1000, " ms")] for r in rows]))
    rows = ex.fig_pi()
    md.append(table("Section 5 - PI (Kp = 300)", ["Ki"] + M, [[r["Ki"]] + metric_cols(r) for r in rows]))
    rows = ex.fig_pd()
    md.append(table("Section 5 - PD (Kp = 300)", ["Kd", "ζ = (10+Kd)/(2√320)", "overshoot from ζ (poles only)"] + M,
                    [[r["Kd"], f"{r['zeta']:.3f}", f"{r['os_pred']:.1f} %"] + metric_cols(r) for r in rows]))

    print("Section 6")
    rows = ex.fig_compare_all()
    md.append(table("Section 6 - P vs PI vs PD vs PID", ["controller", "Kp", "Ki", "Kd"] + M + ["peak force"],
                    [[r["name"], r["Kp"], r["Ki"], r["Kd"]] + metric_cols(r) + [f"{r['peak_u']:.0f} N"] for r in rows]))

    print("Section 7")
    rows = ex.fig_windup()
    md.append(table("Section 7a - Windup (30 N limit)", ["case"] + M, [[r["name"]] + metric_cols(r) for r in rows]))
    rows = ex.fig_noise()
    md.append(table("Section 7b - ±1 mm sensor noise (after t = 1 s)",
                    ["case", "force std", "force peak-to-peak", "position std"],
                    [[r["name"], f"{r['u_std']:.2f} N", f"{r['u_p2p']:.1f} N", f"{r['x_std_mm']:.2f} mm"] for r in rows]))
    rows = ex.fig_kick()
    md.append(table("Section 7c - Derivative kick (step at t = 0.5 s)", ["case", "peak force"] + M,
                    [[r["name"], f"{r['peak_u']:,.0f} N"] + metric_cols(r) for r in rows]))
    rows = ex.fig_sample_time()
    md.append(table("Section 7d - Controller update period", ["update period"] + M,
                    [[f"{r['dt_ms']:g} ms"] + metric_cols(r) for r in rows]))

    print("Section 8")
    zn, rows = ex.fig_ziegler_nichols()
    md.append(f"\n### Section 8 - Ziegler-Nichols\n\nUltimate gain Ku = {zn['ku']:.3f} "
              f"(theory 8.000), period Pu = {zn['pu']:.3f} s (theory 2π/√3 = {zn['pu_theory']:.3f} s)\n")
    md.append(table("Section 8 - Tunings on 1/(s+1)^3", ["tuning", "Kp", "Ki", "Kd"] + M,
                    [[r["name"], f"{r['Kp']:.2f}", f"{r['Ki']:.2f}", f"{r['Kd']:.2f}"] + metric_cols(r) for r in rows]))

    print("Section 9")
    rows = ex.fig_final_controller()
    md.append(table("Section 9 - Final controller", ["case"] + M, [[r["name"]] + metric_cols(r) for r in rows]))

    with open(os.path.join(RES, "results.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print("\nAll done. Tables in results/results.md")


if __name__ == "__main__":
    main()
